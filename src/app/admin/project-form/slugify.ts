/** "The Ramlah Hotel!" → "the-ramlah-hotel". Matches the API's ID rule (lowercase letters, numbers, hyphens). */
export function slugify(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 120);
}
